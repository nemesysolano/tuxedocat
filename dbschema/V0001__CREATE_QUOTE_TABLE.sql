CREATE TABLE QUOTE (
  SYMBOL VARCHAR(20) NOT NULL,
  TIMESTAMP DATETIME NOT NULL,
  OPEN_PRICE DECIMAL(24,15) NOT NULL,
  HIGH_PRICE DECIMAL(24,15) NOT NULL,
  LOW_PRICE DECIMAL(24,15) NOT NULL,
  CLOSE_PRICE DECIMAL(24,15) NOT NULL,
  CONSTRAINT QUOTE_PK PRIMARY KEY (SYMBOL, TIMESTAMP)
);

ALTER TABLE QUOTE ADD COLUMN VOLUME INTEGER;

CREATE OR REPLACE PROCEDURE ADD_QUOTE(
  IN p_SYMBOL VARCHAR(20), 
  IN p_TIMESTAMP TIMESTAMP,
  IN p_OPEN_PRICE DECIMAL(24,15),
  IN p_HIGH_PRICE DECIMAL(24,15),
  IN p_LOW_PRICE DECIMAL(24,15),
  IN p_CLOSE_PRICE DECIMAL(24,15),
  IN p_VOLUME INTEGER
)
LANGUAGE SQL
BEGIN
  MERGE INTO QUOTE AS target
  USING (VALUES (p_SYMBOL, p_TIMESTAMP, p_OPEN_PRICE, p_HIGH_PRICE, p_LOW_PRICE, p_CLOSE_PRICE, p_VOLUME)) 
        AS source (SYMBOL, TIMESTAMP, OPEN_PRICE, HIGH_PRICE, LOW_PRICE, CLOSE_PRICE, VOLUME)
  ON target.SYMBOL = source.SYMBOL AND target.TIMESTAMP = source.TIMESTAMP
  WHEN NOT MATCHED THEN
    INSERT (SYMBOL, TIMESTAMP, OPEN_PRICE, HIGH_PRICE, LOW_PRICE, CLOSE_PRICE, VOLUME)
    VALUES (source.SYMBOL, source.TIMESTAMP, source.OPEN_PRICE, source.HIGH_PRICE, source.LOW_PRICE, source.CLOSE_PRICE, source.VOLUME);
  COMMIT;
END;

